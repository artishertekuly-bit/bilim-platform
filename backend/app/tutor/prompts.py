def suggestions_for(scenario: str) -> list[str]:
    if scenario in SUGGESTIONS:
        return list(SUGGESTIONS[scenario])
    if scenario in _QUESTION_SCENARIOS:
        return list(SUGGESTIONS["QUESTION"])
    return list(SUGGESTIONS["DEFAULT"])


@dataclass(frozen=True)
class NodeLine:
    alias: str
    name: str
    code: str           # ASCII күй коды (§2.3)
    role: str           # focal | parent | bridge | candidate
    description: str
    grade: int | None = None
    paragraph_no: str | None = None
    prerequisites: tuple[str, ...] = ()


def _node_block(nodes: Sequence[NodeLine]) -> str:
    lines = []
    for n in nodes:
        where = f" [{n.grade}-сынып §{n.paragraph_no}]" if n.grade and n.paragraph_no else ""
        prereq = f" prereq:{','.join(n.prerequisites)}" if n.prerequisites else ""
        desc = " ".join(n.description.split())[:MAX_DESCRIPTION_CHARS]
        lines.append(f"{n.alias} {n.role.upper()} {n.name}{where} <{n.code}>{prereq} — {desc}")
    return "\n".join(lines) or "(жоқ)"


def build_reply_messages(
    *,
    scenario: str,
    style: str,
    nodes: Sequence[NodeLine],
    chunks: Sequence[str],
    episodic: Sequence[tuple[str, str]],
    student_text: str,
    digest: str | None = None,
    notes: Sequence[str] = (),
) -> list[Message]:
    scenario_text = SCENARIO_GUIDE[scenario]
    if notes:
        scenario_text += "\n" + "\n".join(f"- {note}" for note in notes)
    textbook = "\n\n---\n\n".join(chunk.strip()[:MAX_CHUNK_CHARS] for chunk in chunks if chunk.strip())
    history = "\n".join(f"{'Оқушы' if role == 'student' else 'Тьютор'}: {text.strip()}" for role, text in episodic)

    context = [
        wrap_untrusted(_node_block(nodes), "nodes"),
        wrap_untrusted(textbook or "(бұл сұраққа оқулық үзіндісі табылмады)", "textbook"),
        wrap_untrusted(history or "(әңгіме енді басталды)", "episodic"),
    ]
    if digest is not None:
        context.append(wrap_untrusted(digest or "(әзірге ештеңе жоқ)", "digest"))
    context.append(f"<scenario>\n{scenario_text}\n</scenario>\n<style>\n{STYLE_GUIDE[style]}\n</style>")

    return [
        Message("system", SYSTEM),
        Message("user", "\n\n".join(context)),
        Message("user", wrap_untrusted(student_text, "student_message")),
    ]
